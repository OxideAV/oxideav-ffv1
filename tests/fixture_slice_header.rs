fn config(extradata: &[u8]) -> Ffv1ConfigurationRecord {
    parse_configuration_record(extradata).expect("test extradata parses")
}

fn assert_default_slice_invariants(h: &oxideav_ffv1::Ffv1SliceHeader, want_x: u32, want_y: u32) {
    // For a 2x2 raster every slice is a 1x1 cell.
    assert_eq!(h.slice_x, want_x, "slice_x");
    assert_eq!(h.slice_y, want_y, "slice_y");
    assert_eq!(h.slice_width, 1, "slice_width raster");
    assert_eq!(h.slice_height, 1, "slice_height raster");
    // 2 quant-table-set indices (chroma_planes=1 + version<=3 → count 2).
    assert_eq!(h.quant_table_set_index_count, 2);
    // Both indices MUST be in `0..quant_table_set_count` (=2 here).
    for &i in h.quant_table_indices() {
        assert!(i < 2, "quant_table_set_index {i} >= quant_table_set_count");
    }
    // Synthetic testsrc → no SAR signalled.
    assert!(
        !h.sar_is_known(),
        "sar_num={} sar_den={}",
        h.sar_num,
        h.sar_den
    );
    // testsrc is progressive video; picture_structure must NOT be
    // a reserved value.
    assert!(matches!(
        h.picture_structure,
        PictureStructure::Unknown
            | PictureStructure::Progressive
            | PictureStructure::TopFieldFirst
            | PictureStructure::BottomFieldFirst
    ));
}

