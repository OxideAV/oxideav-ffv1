//! Slice-header parser fixture tests for FFV1 v3 streams.
//!
//! Each `<fixture>_SLICE<n>` constant below is the byte sub-range of
//! the raw FFV1 frame (the bitstream the container wraps) covering
//! one Slice's range-coded region — i.e. everything BEFORE that
//! Slice's 8-byte SliceFooter (RFC 9043 §4.9, `ec=1` → 8 bytes of
//! footer: u24 slice_size + u8 error_status + u32 slice_crc_parity).
//!
//! The extraction procedure is purely black-box:
//!
//! 1. `ffmpeg -i input.mkv -c copy -map 0:v -f rawvideo frame.bin`
//!    yields the raw FFV1 frame payload (Matroska CodecPrivate plus
//!    the SimpleBlock data, minus container framing).
//! 2. Per RFC 9043 §4.9.1 every slice footer's last 3 bytes hold the
//!    `u(24)` `slice_size` — the size of the slice *excluding* the
//!    footer's 8 bytes. Walking the trailer-pointer chain backwards
//!    from the end of the frame gives each slice's start offset.
//! 3. Each constant below holds `frame.bin[offset .. offset+slice_size]`.
//!
//! No FFV1 spec interpretation is needed for that walk — only the
//! u24-from-last-3-bytes rule, the +8 footer length, and the
//! invariant that slices are emitted in slice-index order (so the
//! `i`-th walk from the end yields slice `slice_count-1-i`).
//!
//! Ground truth for each slice (slice_x, slice_y, slice_w_raster,
//! slice_h_raster) is taken directly from each fixture's `trace.txt`
//! `SLICE` event. Per RFC 9043 §4.6.3 / §4.6.4 the on-wire
//! `slice_width` / `slice_height` are the raster width / height
//! (already +1 vs the wire), so the test expectations are the same
//! values the trace prints.

