//! `Decoder::output_pixel_format` reports the frame layout from the
//! v3 Configuration Record before the first frame, so a pipeline can
//! convert for an encoder even when the container (e.g. Matroska
//! `V_FFV1`) declares no pixel format. Extradata blobs are the
//! `docs/video/ffv1/fixtures/v3-*` Matroska CodecPrivate records.

use oxideav_core::{CodecId, CodecParameters, PixelFormat, RuntimeContext};

const V3_DEFAULT_EXTRADATA: &[u8] = &[
    0x56, 0x00, 0x30, 0x9c, 0x75, 0xdf, 0xf4, 0x60, 0xb4, 0x3a, 0x42, 0xd7, 0xd4, 0xd6, 0x86, 0x2f,
    0x74, 0x92, 0x4a, 0x72, 0xe6, 0x12, 0x9b, 0xf9, 0x2f, 0xba, 0xd1, 0x40, 0x0f, 0x89, 0xac, 0x8f,
    0xc7, 0x82, 0x07, 0xee, 0xbc, 0x31, 0x7c, 0xf5, 0x29, 0x2b,
];

const V3_RGB_BGR0_EXTRADATA: &[u8] = &[
    0x55, 0xf6, 0x46, 0x87, 0xe6, 0xa9, 0xc1, 0x7b, 0x87, 0xbf, 0x82, 0x5e, 0xd8, 0x30, 0x2b, 0x95,
    0x12, 0x2e, 0xcf, 0x70, 0xe2, 0x0f, 0x76, 0xbc, 0x04, 0x17, 0x6c, 0xd6, 0x60, 0xd4, 0x99, 0xbf,
    0x4f, 0x95, 0xdf, 0x58, 0xfb, 0x51, 0xd1, 0x16, 0xf4, 0xad,
];

const V3_GRAYSCALE_EXTRADATA: &[u8] = &[
    0x56, 0x00, 0x2f, 0xd3, 0xc8, 0x18, 0xce, 0x09, 0xeb, 0x7f, 0x68, 0x23, 0xd0, 0x46, 0xc2, 0x44,
    0x28, 0x0a, 0x38, 0x20, 0x41, 0x1c, 0x8f, 0xfd, 0x0b, 0xd7, 0xa0, 0xdd, 0x7d, 0xc7, 0xe2, 0xbe,
    0x16, 0x99, 0xb1, 0xe0, 0xb7, 0x06, 0x5a, 0x9c, 0x7e, 0x09,
];

fn reported(extradata: &[u8]) -> Option<PixelFormat> {
    let mut ctx = RuntimeContext::new();
    oxideav_ffv1::register(&mut ctx);
    let mut p = CodecParameters::video(CodecId::new("ffv1"));
    p.width = Some(64);
    p.height = Some(48);
    p.extradata = extradata.to_vec();
    ctx.codecs
        .first_decoder(&p)
        .expect("decoder")
        .output_pixel_format()
}

#[test]
fn v3_records_report_their_layout() {
    assert_eq!(reported(V3_DEFAULT_EXTRADATA), Some(PixelFormat::Yuv420P));
    assert_eq!(reported(V3_RGB_BGR0_EXTRADATA), Some(PixelFormat::Gbrp8));
    assert_eq!(reported(V3_GRAYSCALE_EXTRADATA), Some(PixelFormat::Gray8));
}

#[test]
fn unconfigured_decoder_reports_nothing() {
    assert_eq!(reported(&[]), None);
}
